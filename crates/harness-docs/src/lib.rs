#![forbid(unsafe_code)]
//! Generates the derivable part of the Harness documentation site, checks every page, and binds
//! a built site to its source commit. The site build itself is Docusaurus.
//!
//! It generates, under `website/`:
//!
//! - the CLI reference ([`cli`], `docs/reference/cli.md`), walked from the clap definition of
//!   `b10x-harness` (`harness_cli::Cli`);
//! - the toolchain reference ([`toolchains`], `docs/reference/toolchains.md`), from the built-in
//!   toolchain specifications `tool_toolchain` ships;
//! - the crate list ([`crates`], `docs/reference/crates.md`), from `cargo metadata --no-deps`;
//! - the status data and page ([`status`], `data/status.json` and `docs/status.md`), from the
//!   capability list this crate holds.
//!
//! The check holds every Markdown page under `website/docs`, generated or written by hand, to
//! the passive-Markdown rule ([`pages`]), to its front matter keys, and to naming nothing that is
//! not public.

pub mod cli;
pub mod crates;
pub mod pages;
pub mod routes;
pub mod status;
pub mod toolchains;

use std::{
    collections::BTreeMap,
    fmt, fs, io,
    path::{Path, PathBuf},
};

/// What went wrong, as one sentence for the operator.
#[derive(Debug)]
pub struct Error(String);

impl fmt::Display for Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

impl std::error::Error for Error {}

impl From<String> for Error {
    fn from(message: String) -> Self {
        Self(message)
    }
}

impl From<&str> for Error {
    fn from(message: &str) -> Self {
        Self(message.to_owned())
    }
}

impl From<io::Error> for Error {
    fn from(error: io::Error) -> Self {
        Self(error.to_string())
    }
}

impl From<serde_json::Error> for Error {
    fn from(error: serde_json::Error) -> Self {
        Self(error.to_string())
    }
}

impl From<std::path::StripPrefixError> for Error {
    fn from(error: std::path::StripPrefixError) -> Self {
        Self(error.to_string())
    }
}

/// This crate's result.
pub type Result<T> = std::result::Result<T, Error>;

/// Adds what was being done to a failure, as `<what>: <failure>`.
pub trait Context<T> {
    /// # Errors
    ///
    /// The failure, prefixed with `what`.
    fn context(self, what: &str) -> Result<T>;
    /// # Errors
    ///
    /// The failure, prefixed with what `what` returns.
    fn with_context(self, what: impl FnOnce() -> String) -> Result<T>;
}

impl<T, E: fmt::Display> Context<T> for std::result::Result<T, E> {
    fn context(self, what: &str) -> Result<T> {
        self.map_err(|error| Error(format!("{what}: {error}")))
    }
    fn with_context(self, what: impl FnOnce() -> String) -> Result<T> {
        self.map_err(|error| Error(format!("{}: {error}", what())))
    }
}

impl<T> Context<T> for Option<T> {
    fn context(self, what: &str) -> Result<T> {
        self.ok_or_else(|| Error(what.to_owned()))
    }
    fn with_context(self, what: impl FnOnce() -> String) -> Result<T> {
        self.ok_or_else(|| Error(what()))
    }
}

/// Returns an [`Error`] built with `format!` unless the condition holds.
macro_rules! ensure {
    ($condition:expr, $($message:tt)+) => {
        if !$condition {
            return Err($crate::Error::from(format!($($message)+)));
        }
    };
}
/// Returns an [`Error`] built with `format!`.
macro_rules! bail {
    ($($message:tt)+) => {
        return Err($crate::Error::from(format!($($message)+)))
    };
}
pub(crate) use {bail, ensure};

/// The first line of every generated page's front matter.
pub const FRONT_MATTER_HEADER: &str = "# generated by harness-docs, do not edit";
/// The line every generated Markdown page carries directly after its front matter.
pub const HEADER: &str = "<!-- generated by harness-docs, do not edit -->";
/// A file in the repository on GitHub, by path.
pub const SOURCE: &str = "https://github.com/beyond10x/harness/blob/main";
/// A directory in the repository on GitHub, by path.
pub const TREE: &str = "https://github.com/beyond10x/harness/tree/main";
/// The reference directory, relative to the repository root. Every file in it is generated
/// except [`HAND_WRITTEN_REFERENCE`].
pub const REFERENCE: &str = "website/docs/reference";
/// The reference pages written by hand: what they describe has no definition to generate from.
pub const HAND_WRITTEN_REFERENCE: &[&str] = &["configuration.md", "wires.md"];
/// Every documentation page, generated or written by hand, relative to the repository root.
pub const DOCS: &str = "website/docs";
/// The page that must name the release it documents.
pub const LANDING: &str = "website/docs/index.md";
/// The workspace version this build documents.
pub const VERSION: &str = env!("CARGO_PKG_VERSION");

/// The front matter every page carries.
const KEYS: &[&str] = &["title", "sidebar_position", "description"];
/// The front matter a concept or guide page carries besides [`KEYS`]: the sentence the page
/// opens on, and what in the repository it is written from.
const NARRATIVE_KEYS: &[&str] = &["lede", "source"];
/// The directories whose pages carry [`NARRATIVE_KEYS`], relative to [`DOCS`].
const NARRATIVE: &[&str] = &["concepts/", "guides/"];

/// Internal material a public page must not point at.
const FORBIDDEN_PUBLIC_REFERENCES: &[&str] = &[
    "docs/design",
    ".engineering",
    "STATUS.md",
    "ROADMAP.md",
    "beyond10x/atlas",
    "../atlas",
];

/// Generated files keyed by their path relative to the repository root.
pub type Outputs = BTreeMap<String, String>;

/// The repository root of this crate's own checkout.
#[must_use]
pub fn repository_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

/// `value` as a double-quoted YAML string.
#[must_use]
pub fn yaml_string(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
}

/// `value` as one Markdown table cell: on one line, with `|` escaped, and passive outside code.
#[must_use]
pub fn cell(value: &str) -> String {
    prose(
        &value
            .split_whitespace()
            .collect::<Vec<_>>()
            .join(" ")
            .replace('|', "\\|"),
    )
}

/// `text` with what MDX would execute escaped outside its code spans: `{` as `\{`, and the `<`
/// that opens a tag as `&lt;`, so that a placeholder such as `<name>` in prose is shown, not
/// taken as HTML.
#[must_use]
pub fn prose(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(start) = rest.find('`') {
        out.push_str(&escape(&rest[..start]));
        let run = rest[start..].bytes().take_while(|b| *b == b'`').count();
        let after = &rest[start + run..];
        if let Some(end) = pages::span_end(after, run) {
            out.push_str(&rest[start..start + run + end + run]);
            rest = &after[end + run..];
        } else {
            out.push_str(&rest[start..start + run]);
            rest = after;
        }
    }
    out.push_str(&escape(rest));
    out
}

fn escape(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for (at, c) in text.char_indices() {
        match c {
            '{' => out.push_str("\\{"),
            '<' if text[at + 1..]
                .trim_start_matches('/')
                .starts_with(|c: char| c.is_ascii_alphabetic()) =>
            {
                out.push_str("&lt;");
            }
            _ => out.push(c),
        }
    }
    out
}

/// The front matter of a generated page and its generator line.
#[must_use]
pub fn front_matter(title: &str, position: u32, description: &str) -> String {
    format!(
        "---\n{FRONT_MATTER_HEADER}\ntitle: {}\nsidebar_position: {position}\ndescription: {}\ncustom_edit_url: null\n---\n\n{HEADER}\n\n",
        yaml_string(title),
        yaml_string(description),
    )
}

/// Every generated file for the repository at `root`, each Markdown page checked passive.
///
/// # Errors
///
/// When a source cannot be read, a shipped capability names a test that does not exist, or a
/// page would hold what the unified site refuses.
pub fn outputs(root: &Path) -> Result<Outputs> {
    let mut out = Outputs::new();
    out.insert(cli::PAGE.to_owned(), cli::page());
    out.insert(toolchains::PAGE.to_owned(), toolchains::page()?);
    out.insert(crates::PAGE.to_owned(), crates::page(root)?);
    out.insert(status::DATA.to_owned(), status::data(root)?);
    out.insert(status::PAGE.to_owned(), status::page(root)?);
    for (path, content) in &out {
        if Path::new(path).extension().is_some_and(|ext| ext == "md") {
            let problems = page_problems(path, content);
            ensure!(
                problems.is_empty(),
                "{path} would not be a valid page: {}",
                problems.join(", ")
            );
            ensure!(!content.contains("story:"), "{path} would name a story");
        }
    }
    Ok(out)
}

/// Writes `outputs` under `out`. The hand-written reference pages are left as they are.
///
/// # Errors
///
/// When a file cannot be written.
pub fn write(outputs: &Outputs, out: &Path) -> Result<()> {
    for (path, content) in outputs {
        let target = out.join(path);
        if let Some(dir) = target.parent() {
            fs::create_dir_all(dir).with_context(|| format!("creating {}", dir.display()))?;
        }
        fs::write(&target, content).with_context(|| format!("writing {}", target.display()))?;
    }
    Ok(())
}

/// Every file under `dir`, relative to `base`, with `/` separators.
fn files_under(base: &Path, dir: &Path, found: &mut Vec<String>) -> Result<()> {
    if !dir.is_dir() {
        return Ok(());
    }
    let mut entries: Vec<_> = fs::read_dir(dir)
        .with_context(|| format!("reading {}", dir.display()))?
        .collect::<std::result::Result<_, _>>()?;
    entries.sort_by_key(fs::DirEntry::path);
    for entry in entries {
        let path = entry.path();
        if path.is_dir() {
            files_under(base, &path, found)?;
        } else {
            found.push(
                path.strip_prefix(base)?
                    .to_string_lossy()
                    .replace('\\', "/"),
            );
        }
    }
    Ok(())
}

/// The keys of the front matter of `source`, or `None` when it has none.
fn front_matter_keys(source: &str) -> Option<Vec<&str>> {
    let rest = source.strip_prefix("---\n")?;
    let end = rest.find("\n---\n")?;
    Some(
        rest[..end]
            .lines()
            .filter(|line| !line.starts_with(['#', ' ', '-']))
            .filter_map(|line| line.split_once(':').map(|(key, _)| key.trim()))
            .collect(),
    )
}

/// The front matter keys whose unquoted value YAML would not read as the one string written: a
/// `: ` or ` #` inside it, or a first character YAML reserves or reads as another type. The site
/// build refuses such a page with a parser error far from the page's own name.
fn unquoted_values(source: &str) -> Vec<&str> {
    let Some(rest) = source.strip_prefix("---\n") else {
        return Vec::new();
    };
    let Some(end) = rest.find("\n---\n") else {
        return Vec::new();
    };
    rest[..end]
        .lines()
        .filter(|line| !line.starts_with(['#', ' ', '-']))
        .filter_map(|line| line.split_once(':'))
        .filter(|(_, value)| {
            let value = value.trim();
            !value.starts_with(['"', '\''])
                && (value.contains(": ")
                    || value.contains(" #")
                    || value.ends_with(':')
                    || value.starts_with(['`', '@', '%', '&', '*', '!', '|', '>', '{', '[']))
        })
        .map(|(key, _)| key.trim())
        .collect()
}

/// Every problem of the page at `path` (relative to the repository root) whose text is `text`:
/// a missing front matter key, a front matter value YAML would misread, a reference to internal
/// material, and every place it is not passive Markdown.
fn page_problems(path: &str, text: &str) -> Vec<String> {
    let mut problems = Vec::new();
    let relative = path
        .strip_prefix(DOCS)
        .unwrap_or(path)
        .trim_start_matches('/');
    for key in unquoted_values(text) {
        problems.push(format!(
            "{path}: front matter {key} needs quotes: YAML would not read its value as one string"
        ));
    }
    match front_matter_keys(text) {
        None => problems.push(format!("{path}: no front matter")),
        Some(keys) => {
            let narrative = NARRATIVE.iter().any(|dir| relative.starts_with(dir));
            let required = KEYS
                .iter()
                .chain(NARRATIVE_KEYS.iter().filter(|_| narrative));
            for key in required {
                if !keys.contains(key) {
                    problems.push(format!("{path}: no {key}"));
                }
            }
        }
    }
    for forbidden in FORBIDDEN_PUBLIC_REFERENCES {
        if text.contains(forbidden) {
            problems.push(format!(
                "{path}: names `{forbidden}`, which is not public material"
            ));
        }
    }
    for problem in pages::problems(text) {
        problems.push(format!("{path}:{problem}"));
    }
    problems
}

/// Every difference between `outputs` and the files under `out`: a missing file, a stale or
/// edited one, a file under [`REFERENCE`] that is neither generated nor hand-written, every page
/// problem under [`DOCS`], and a landing page that does not name [`VERSION`].
///
/// # Errors
///
/// When a directory cannot be read.
pub fn check(outputs: &Outputs, out: &Path) -> Result<Vec<String>> {
    let mut problems = Vec::new();
    for (path, content) in outputs {
        match fs::read_to_string(out.join(path)) {
            Err(_) => problems.push(format!("missing {path}")),
            Ok(found) if &found != content => problems.push(format!("stale or edited {path}")),
            Ok(_) => {}
        }
    }
    let mut present = Vec::new();
    files_under(out, &out.join(REFERENCE), &mut present)?;
    for path in present {
        let hand_written = HAND_WRITTEN_REFERENCE
            .iter()
            .any(|name| path == format!("{REFERENCE}/{name}"));
        if !outputs.contains_key(&path) && !hand_written {
            problems.push(format!("not generated {path}"));
        }
    }
    let mut docs = Vec::new();
    files_under(out, &out.join(DOCS), &mut docs)?;
    for path in docs.iter().filter(|path| {
        Path::new(path)
            .extension()
            .is_some_and(|ext| ext == "md" || ext == "mdx")
    }) {
        let text = fs::read_to_string(out.join(path))?;
        if Path::new(path)
            .extension()
            .is_some_and(|ext| ext.eq_ignore_ascii_case("mdx"))
        {
            problems.push(format!("{path}: an MDX page (write it as plain .md)"));
        }
        problems.extend(page_problems(path, &text));
    }
    match fs::read_to_string(out.join(LANDING)) {
        Ok(landing) if !landing.contains(VERSION) => problems.push(format!(
            "{LANDING} does not name the workspace version {VERSION}"
        )),
        Ok(_) => {}
        Err(_) => problems.push(format!("missing {LANDING}")),
    }
    Ok(problems)
}

/// The project-site publication record for one build of the `/harness/` site.
///
/// # Errors
///
/// When `commit` is not a nonzero full Git revision in lowercase hex.
pub fn site_manifest(commit: &str) -> Result<String> {
    ensure!(
        commit.len() == 40
            && commit
                .bytes()
                .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
            && commit != "0".repeat(40),
        "commit must be a nonzero full Git revision, 40 lowercase hex digits"
    );
    Ok(format!(
        "{{\n  \"baseUrl\": \"{}\",\n  \"commit\": \"{commit}\",\n  \"repository\": \"harness\",\n  \"schema\": \"b10x-project-site/v1\"\n}}",
        routes::BASE
    ))
}

/// Binds the built site at `site` to `commit`: `.well-known/b10x-site.json`, the route inventory
/// `.well-known/b10x-routes.json` and `.nojekyll`.
///
/// # Errors
///
/// When the commit is not a full revision, `site` holds no built site, or a file cannot be
/// written.
pub fn write_provenance(site: &Path, commit: &str) -> Result<()> {
    let manifest = site_manifest(commit)?;
    ensure!(
        site.join("index.html").is_file(),
        "{} holds no built site",
        site.display()
    );
    let inventory = routes::inventory(site, commit)?;
    fs::create_dir_all(site.join(".well-known"))?;
    fs::write(site.join(".well-known/b10x-site.json"), manifest)
        .context("writing site provenance")?;
    fs::write(site.join(".well-known/b10x-routes.json"), inventory)
        .context("writing the route inventory")?;
    fs::write(site.join(".nojekyll"), "")?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn prose_escapes_braces_and_capitalised_tags_outside_code_only() {
        assert_eq!(
            prose("a {b} `{c}` <D> `<E>` <f> </G>"),
            "a \\{b} `{c}` &lt;D> `<E>` &lt;f> &lt;/G>"
        );
        assert!(pages::problems(&prose("x { y <Z> `{`")).is_empty());
    }

    #[test]
    fn a_manifest_names_the_commit_and_refuses_a_bad_one() {
        let commit = "e86f43d90b637fc2c1790f77d59efff2eb852386";
        assert!(
            site_manifest(commit)
                .unwrap()
                .contains(&format!("\"commit\": \"{commit}\""))
        );
        assert!(site_manifest("e86f43d").is_err());
        assert!(site_manifest(&"0".repeat(40)).is_err());
        assert!(site_manifest(&format!("{}\"", &commit[..39])).is_err());
        assert!(
            site_manifest(&commit.to_uppercase()).is_err(),
            "a revision is lowercase hex, as Git prints it and the publisher compares it"
        );
    }

    #[test]
    fn a_front_matter_value_yaml_would_misread_is_named() {
        let page = "---\ntitle: T\nsidebar_position: 1\ndescription: Covers this: and that\n\
                    lede: \"Quoted: fine\"\nsource: `b10x-harness --help`\n---\n\nBody.\n";
        assert_eq!(
            page_problems("website/docs/reference/x.md", page),
            [
                "website/docs/reference/x.md: front matter description needs quotes: YAML would \
                 not read its value as one string",
                "website/docs/reference/x.md: front matter source needs quotes: YAML would not \
                 read its value as one string",
            ]
        );
        let generated = front_matter("A: b", 1, "c # d");
        assert!(unquoted_values(&format!("{generated}\nBody.\n")).is_empty());
    }

    #[test]
    fn a_narrative_page_needs_its_lede_and_source_and_a_reference_page_does_not() {
        let plain = "---\ntitle: T\nsidebar_position: 1\ndescription: D\n---\n\nBody.\n";
        assert!(page_problems("website/docs/reference/x.md", plain).is_empty());
        assert_eq!(
            page_problems("website/docs/concepts/x.md", plain),
            [
                "website/docs/concepts/x.md: no lede",
                "website/docs/concepts/x.md: no source"
            ]
        );
    }

    #[test]
    fn internal_material_is_named() {
        let page = "---\ntitle: T\nsidebar_position: 1\ndescription: D\n---\n\nSee ROADMAP.md.\n";
        assert_eq!(
            page_problems("website/docs/x.md", page),
            ["website/docs/x.md: names `ROADMAP.md`, which is not public material"]
        );
    }
}
