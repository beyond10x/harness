//! The toolchain reference page, from the built-in toolchain specifications `tool_toolchain`
//! ships (`tool_toolchain::builtin_reference`).
//!
//! That function returns a whole page under its own front matter and generator line. This module
//! keeps its body and replaces both, failing when their shape changes, so a new release of the
//! tools crates cannot slip a second front matter or a stale generator name onto the page.

use crate::{Result, front_matter};

/// Where the toolchain reference lands, relative to the repository root.
pub const PAGE: &str = "website/docs/reference/toolchains.md";

/// What `tool_toolchain::builtin_reference` puts before the body.
const UPSTREAM_PREFIX: &str =
    "---\ntitle: Toolchains\n---\n\n<!-- Generated by `cargo xtask toolchain-docs`. -->\n\n";

/// The toolchain page for the body `upstream` returns.
fn page_for(upstream: &str) -> Result<String> {
    let Some(body) = upstream.strip_prefix(UPSTREAM_PREFIX) else {
        return Err(
            "tool_toolchain::builtin_reference no longer starts with the front matter this \
             generator replaces; read its output and update UPSTREAM_PREFIX"
                .into(),
        );
    };
    Ok(format!(
        "{}# Toolchains\n\n{body}",
        front_matter(
            "Toolchains",
            3,
            "Every built-in toolchain provider, its project markers and the dedicated tools it publishes.",
        )
    ))
}

/// The toolchain reference page.
///
/// # Errors
///
/// When the built-in specifications do not load or the upstream page changed shape.
pub fn page() -> Result<String> {
    page_for(&tool_toolchain::builtin_reference()?)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn an_upstream_page_of_another_shape_is_refused() {
        assert!(page_for("---\ntitle: Other\n---\n\nbody\n").is_err());
        let page = page_for(&format!("{UPSTREAM_PREFIX}Body.\n")).unwrap();
        assert!(page.ends_with("# Toolchains\n\nBody.\n"), "{page}");
    }
}
