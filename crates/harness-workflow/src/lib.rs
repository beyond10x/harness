//! One loop walks a whole workflow: a step is a turn, a section is a conversation.
//!
//! # Why this is a crate of its own
//!
//! [`harness_flow`] can plan and walk a document and deliberately knows nothing about a model, a
//! credential or a tool: what a step *is* lives behind [`StepRunner`](harness_flow::StepRunner).
//! The one implementation that binds a step to the loop used to live inside the command-line
//! binary, so the only way to walk a document natively was to start that binary. This crate is
//! that implementation with everything process- and terminal-shaped taken out: a library caller
//! hands [`Walk`] a model port, a toolset, an approver and a document, and gets the walk's
//! [`Report`] and its events back, with no `b10x-harness` process anywhere.
//!
//! # What a walk is, in three sentences
//!
//! [`Walk`] binds a step to one [`AgentLoop::run_in`](harness_loop::AgentLoop::run_in) over the
//! ports its caller lent it: one client, one catalogue, one approver, one gate. A **group is a
//! conversation**: every step with the same `scope` and `attempt` continues the same items, and a
//! new scope starts from what its siblings promised and nothing else. Every step runs under a
//! schema this crate derives ([`answer_schema`]), so a step says *passed* or *failed* by calling
//! `answer` rather than by being read out of prose.
//!
//! # What the caller supplies, and what this crate never does
//!
//! Three collaborators are the caller's, each as a narrow trait this crate defines:
//!
//! - a [`Governor`], asked at every section boundary whether it may be crossed. With none, every
//!   boundary proceeds and **no** [`LoopEvent::HookRan`](harness_loop::LoopEvent::HookRan) is
//!   recorded, because a record showing a gate at every boundary of an ungoverned run would be a
//!   gate a reader believes was there;
//! - a [`StepRecord`], told when a section's conversation opens, grows and closes, so the caller
//!   can file it wherever its sessions live;
//! - two event sinks, a [`FlowSink`] for the walk and a [`LoopSink`] for the loop, which a caller
//!   with one stream may point at the same renderer.
//!
//! **This crate spawns no process and reads no file its caller did not hand it.** A `command`
//! step is one `run` call through the toolset the caller lent; a hook is whatever
//! [`HookPort`] the caller attached; a step's `context` files are read only from inside the
//! workspace the caller named with [`Walk::with_workspace`], and a walk given none refuses a step
//! that names one.
//!
//! # A step runs under the write scope its own node declares
//!
//! The one thing about the toolset that is **not** the run's for every step. A node's
//! `run.scope` — the map's own first-match-wins list, in the grammar `--write-scope` takes — is
//! laid over the run's for the length of that step and taken off again however it ends
//! ([`harness_catalogue::Catalogue::narrow`]). It can only narrow: both layers are asked and the
//! first refusal wins, so a document generated by another component cannot give back what the
//! operator took away, and a node declaring nothing runs under the run's exactly as every step
//! did. A `scope` this build cannot read refuses the document by node path in
//! [`check_payloads`], never falling through to the run's.
//!
//! # A `command` step is a call, not a turn
//!
//! A step whose `run` says `kind: command` names a program the document runs — the projection's
//! verifiers, `producer: verifier` — and no model is asked anything (design 0003 § 6, M2). The
//! argv becomes one `run` call made through
//! [`AgentLoop::call`](harness_loop::AgentLoop::call), which is the gate a model's call meets in
//! the order it meets it: published, the approver, the operator's `before-call` hook, the tool,
//! `after-call`. The call and its result are filed into the section's conversation exactly as a
//! model's would be; exit `0` is a passed step and anything else — a non-zero exit, a timeout, a
//! refusal at any stage — is a failed one, with the reason in the record beside it.
//!
//! # The cost and duration ceilings bound the walk, not the step
//!
//! Every other bound in the caller's [`LoopConfig`] is per step, because that is what one
//! `run_in` counts. Money and wall clock are not like that — a caller who says *spend at most a
//! dollar* means the walk (design 0003 § 2). `run_in` **replaces** the ledger it is lent, so the
//! arithmetic is here: the walk keeps its own cumulative ledger and the instant it began, and
//! before each step derives that step's [`Budget`](harness_loop::Budget) from what **remains**. A
//! step that would start with nothing left never starts: it is `Failed`, with a `flow-budget`
//! warning naming the ceiling and the spend, and no model is asked anything.

