/// A toolset a walk can narrow for one step.
///
/// A [`ToolPort`] and the one [`Catalogue`] behind it, because the write scope a step's node
/// declares lives on the catalogue and is laid over the run's for the length of that step. Both
/// surfaces [`harness_catalogue`] ships implement it here, and a caller that wraps one of them in
/// its own port implements it by handing back the catalogue inside.
pub trait StepTools: ToolPort {
    /// The catalogue every published tool reaches.
    fn catalogue(&self) -> &Catalogue;

    /// The same catalogue, to narrow for one step.
    fn catalogue_mut(&mut self) -> &mut Catalogue;
}

impl StepTools for Flat {
    fn catalogue(&self) -> &Catalogue {
        Flat::catalogue(self)
    }

    fn catalogue_mut(&mut self) -> &mut Catalogue {
        Flat::catalogue_mut(self)
    }
}

impl StepTools for Verbs {
    fn catalogue(&self) -> &Catalogue {
        Verbs::catalogue(self)
    }

    fn catalogue_mut(&mut self) -> &mut Catalogue {
        Verbs::catalogue_mut(self)
    }
}

/// One attempt of one section: the conversation a [`StepRecord`] is told about.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Section<'a> {
    /// The section's path, `root.implement-to-review.review`.
    pub path: &'a str,
    /// Which attempt of it, from 1.
    pub attempt: u32,
}

/// A section boundary a [`Governor`] is asked about.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Transition<'a> {
    /// The document's own name.
    pub flow: &'a str,
    /// The section's path.
    pub path: &'a str,
    /// Which side of the boundary the walk is standing on.
    pub moment: Moment,
    /// The attempt being asked about, from 1.
    pub attempt: u32,
    /// How many attempts the document allows this section, as the plan reconciled them.
    pub of: u32,
    /// At [`Moment::Leave`], whether the attempt failed and what it is handing over; [`None`] at
    /// [`Moment::Enter`], where neither exists yet.
    pub leave: Option<(bool, &'a Handoff)>,
}

/// Whoever decides whether a section boundary may be crossed (design 0003 § 3).
///
/// **The walk evaluates no gate**: it asks, records the answer as a
/// [`LoopEvent::HookRan`](harness_loop::LoopEvent::HookRan) at
/// [`HookPoint::Transition`](harness_loop::HookPoint::Transition), and carries the words. A
/// [`HookDecision::Block`] and a [`HookDecision::Failed`] are both a refusal at either moment: a
/// governor that could not answer did not say yes.
pub trait Governor {
    /// The answer for one crossing; anything but [`HookDecision::Proceed`] refuses it.
    fn transition(&mut self, transition: &Transition<'_>) -> HookDecision;
}

/// Where a walk files each section's conversation.
///
/// Told in the order things happen, and strictly nested: a section is opened after its governor
/// let it in, closed when it is left **before** the governor is asked about leaving it — a refused
/// attempt still happened and still cost what it cost, and a governor that declines a result must
/// not be able to delete the transcript of it — and never closed if it was never opened.
pub trait StepRecord {
    /// A section's attempt began. `above` is every section open around it, outermost first.
    fn opened(&mut self, section: Section<'_>, above: &[Section<'_>]);

    /// A step of the section finished a run of the loop; `outcome.items` is the section's whole
    /// conversation now.
    fn answered(&mut self, section: Section<'_>, outcome: &LoopOutcome);

    /// A `command` step filed its call and its result; `items` is the section's whole conversation
    /// now.
    fn called(&mut self, section: Section<'_>, items: &[Item]);

    /// A step of the section broke on the wire: the conversation the loop handed back, and what
    /// it cost before it broke.
    fn broke(&mut self, section: Section<'_>, items: &[Item], spent: &RunLedger);

    /// The section's attempt ended.
    fn closed(&mut self, section: Section<'_>);
}

/// Why a walk produced no [`Report`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum WalkError {
    /// Nothing was sent: the document does not plan, or a step payload is not one this runner
    /// reads.
    Refused(String),
    /// A step broke on the wire and the walk stopped where it stood. A broken wire is nobody's
    /// failed step, and a walk that recorded it as `Failed` would misreport the plan.
    Aborted(String),
}

impl fmt::Display for WalkError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Refused(reason) | Self::Aborted(reason) => formatter.write_str(reason),
        }
    }
}

impl std::error::Error for WalkError {}

/// A walk of one document over ports its caller lent it.
///
/// One client, one catalogue, one approver and one gate for the whole walk, because a section
/// that published its own toolset would be a second answer to *what may this run do* (design
/// 0003 § 6). The catalogue's **write scope** is the exception: each step narrows it to what its
/// own node declares and gives it back when it ends (crate header).
pub struct Walk<'a> {
    model: &'a mut dyn ModelPort,
    tools: &'a mut dyn StepTools,
    approvals: &'a mut dyn ApprovalPort,
    config: LoopConfig,
    cancel: LoopCancel,
    hooks: Option<&'a mut dyn HookPort>,
    governor: Option<&'a mut dyn Governor>,
    record: Option<&'a mut dyn StepRecord>,
    workspace: Option<&'a Path>,
}

impl<'a> Walk<'a> {
    /// A walk with no governor, no record, no hooks and no workspace.
    ///
    /// `config` is cloned per step, exactly as a single run uses it: each step replaces the output
    /// schema with its own section's and the budget with what the walk has left. Its instructions
    /// are the caller's, and a caller that wants a step told to finish by calling `answer` writes
    /// that sentence there.
    pub fn new(
        model: &'a mut dyn ModelPort,
        tools: &'a mut dyn StepTools,
        approvals: &'a mut dyn ApprovalPort,
        config: LoopConfig,
    ) -> Self {
        Self {
            model,
            tools,
            approvals,
            config,
            cancel: LoopCancel::new(),
            hooks: None,
            governor: None,
            record: None,
            workspace: None,
        }
    }

    /// Lends every step this cancellation handle.
    #[must_use]
    pub fn with_cancel(mut self, cancel: LoopCancel) -> Self {
        self.cancel = cancel;
        self
    }

    /// The operator's hooks, which the loop consults at its own three points in every step.
    #[must_use]
    pub fn with_hooks(mut self, hooks: &'a mut dyn HookPort) -> Self {
        self.hooks = Some(hooks);
        self
    }

    /// Whoever is asked at every section boundary.
    #[must_use]
    pub fn with_governor(mut self, governor: &'a mut dyn Governor) -> Self {
        self.governor = Some(governor);
        self
    }

    /// Where each section's conversation is filed.
    #[must_use]
    pub fn with_record(mut self, record: &'a mut dyn StepRecord) -> Self {
        self.record = Some(record);
        self
    }

    /// The directory a step's `context` files are read from, and the boundary they must resolve
    /// inside.
    #[must_use]
    pub fn with_workspace(mut self, workspace: &'a Path) -> Self {
        self.workspace = Some(workspace);
        self
    }

    /// Walks `flow` with `input` as the task every step is given beside its own prompt.
    ///
    /// The walk's events go to `flow_events` and the loop's to `loop_events`. Once a step is
    /// cancelled or breaks on the wire **nothing more reaches `flow_events`**, `flow-finished`
    /// included: the walk has no word for stopping where it stands, and the skips and section
    /// ends it would go on emitting describe things that did not happen.
    ///
    /// # Errors
    ///
    /// [`WalkError::Refused`] before anything is sent, for a document that does not plan or
    /// carries a payload [`check_payloads`] refuses. [`WalkError::Aborted`] when a step broke on
    /// the wire.
    pub fn run(
        &mut self,
        flow: &Flow,
        input: &str,
        flow_events: &mut dyn FlowSink,
        loop_events: &mut dyn LoopSink,
    ) -> Result<Report, WalkError> {
        let plan = flow
            .plan()
            .map_err(|error| WalkError::Refused(error.to_string()))?;
        check_payloads(flow).map_err(WalkError::Refused)?;
        let halted = Cell::new(false);
        let mut walker = runner::Runner {
            walk: self,
            flow: &flow.id,
            input,
            promises: document::promises(&flow.root, &flow.root.id),
            bounds: bounds(&plan),
            open: Vec::new(),
            spend: RunLedger::default(),
            started: Instant::now(),
            events: loop_events,
            halted: &halted,
            aborted: None,
            commands: 0,
        };
        let mut record = runner::Halting {
            events: flow_events,
            halted: &halted,
        };
        // The document planned above, so this cannot refuse; it is mapped rather than unwrapped
        // because a panic here would be this crate asserting something the notation owns.
        let report = flow
            .run(&mut walker, &mut record)
            .map_err(|error| WalkError::Refused(error.to_string()))?;
        if let Some(error) = walker.aborted {
            return Err(WalkError::Aborted(error));
        }
        Ok(report)
    }
}
